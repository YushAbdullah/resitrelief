// Builds dist/ (a full HTML page you can host anywhere) and the shared files the Supabase functions use.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), out = path.join(root, 'dist');
fs.mkdirSync(out, { recursive: true });
const body = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
fs.writeFileSync(path.join(out, 'index.html'), `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="Keep every receipt, sort it into LHDN tax reliefs, and track your spending.">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}[hidden]{display:none!important}img{max-width:100%}</style>
</head><body>
${body}
</body></html>
`);
for (const f of ['config.js', 'store.js', 'reliefs.js', 'engine.js', 'app.js']) fs.copyFileSync(path.join(root, f), path.join(out, f));
fs.cpSync(path.join(root, 'brand'), path.join(out, 'brand'), { recursive: true });
fs.cpSync(path.join(root, 'vendor'), path.join(out, 'vendor'), { recursive: true });

// Supabase Edge Functions run Deno ES modules: wrap the shared engine once.
const shared = path.join(root, 'supabase/functions/_shared');
fs.mkdirSync(shared, { recursive: true });
fs.writeFileSync(path.join(shared, 'engine.js'), '// Generated by scripts/build.js from engine.js. Do not edit.\nconst module = { exports: {} };\n' +
  fs.readFileSync(path.join(root, 'engine.js'), 'utf8') + '\nexport default module.exports;\n');

// Seed SQL for the relief_rules table from the bundled rules (version 1).
const { RELIEFS } = require(path.join(root, 'reliefs.js'));
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const seed = Object.entries(RELIEFS).map(([ya, rules]) =>
  `insert into public.relief_rules (ya, version, rules, note, source_url, is_active) values (${ya}, 1, ${q(JSON.stringify(rules))}::jsonb, ${q('Initial rules from PwC Malaysian Tax Booklet 2026/2027')}, ${q('https://www.pwc.com/my/en/publications/mtb/personal-income-tax.html')}, true) on conflict do nothing;`).join('\n');
fs.writeFileSync(path.join(root, 'supabase/seed.sql'), '-- Generated by scripts/build.js. Run after schema.sql.\n' + seed + '\n');
console.log('Built dist/, supabase/functions/_shared/engine.js and supabase/seed.sql');
